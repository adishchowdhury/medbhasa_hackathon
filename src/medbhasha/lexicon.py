_HYPHEN_SUFFIXES = {"এর", "তে", "এ", "র", "কে", "য়", "য়ের", "টি", "টা", "ও", "ই", "সহ", "দের", "গুলো", "য়ে", "ের"}


def norm(tok: str) -> str:
    """Normalise a token for gazetteer matching (spelling variants, case endings, hyphen suffixes)."""
    t = unicodedata.normalize("NFC", tok)
    t = t.replace("‍", "").replace("‌", "").replace("​", "")
    # compose nukta forms that NFC leaves decomposed: ড+় -> ড়, ঢ+় -> ঢ়, য+় -> য়
    t = t.replace("\u09a1\u09bc", "\u09dc").replace("\u09a2\u09bc", "\u09dd").replace("\u09af\u09bc", "\u09df")
    t = t.lower()
    # drop hyphen-attached suffix: ইসিজি-তে -> ইসিজি ; ডায়াবেটিস-এর -> ডায়াবেটিস
    if "-" in t:
        head, _, tail = t.rpartition("-")
        if len(head) >= 2 and tail in _HYPHEN_SUFFIXES:
            t = head
    return t


_CASE = ("গুলো", "দের", "ের", "তে", "েতে", "কে", "টি", "টা", "য়", "ে", "র", "এ")


def stem(tok: str) -> str:
    t = norm(tok)
    for suf in _CASE:
        if t.endswith(suf) and len(t) - len(suf) >= 3:
            return t[: -len(suf)]
    return t


def _build():
    gaz = {}
    maxlen = 1
    for ty, blob in _RAW.items():
        for term in re.split(r"[|\n]+", blob):
            term = term.strip()
            if not term:
                continue
            parts = tuple(norm(p) for p in term.split())
            parts_s = tuple(stem(p) for p in term.split())
            maxlen = max(maxlen, len(parts))
            gaz.setdefault(parts, set()).add(ty)
            gaz.setdefault(parts_s, set()).add(ty)
    return gaz, maxlen


GAZ, MAXLEN = _build()


def match(tokens):
    """Greedy longest-match gazetteer lookup.

    Returns per-token lists of ``(type, 'B'|'I')`` marks.
    """
    n = len(tokens)
    normed = [norm(t) for t in tokens]
    stemmed = [stem(t) for t in tokens]
    marks = [[] for _ in range(n)]
    i = 0
    while i < n:
        hit = None
        for L in range(min(MAXLEN, n - i), 0, -1):
            key1 = tuple(normed[i:i + L])
            key2 = tuple(stemmed[i:i + L])
            types = GAZ.get(key1) or GAZ.get(key2)
            if types:
                # single very short tokens are too ambiguous (e.g. 'না', 'র', 'পর')
                hit = (L, types)
                break
        if hit:
            L, types = hit
            for t in sorted(types):
                marks[i].append((t, "B"))
                for k in range(1, L):
                    marks[i + k].append((t, "I"))
            i += L
        else:
            i += 1
    return marks
