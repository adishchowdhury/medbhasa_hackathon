#!/usr/bin/env python3
"""Build the final annotated corpus + metadata from the sources.

Inputs
  data/round1/round1_submitted_annotated_corpus.csv   (the 40 notes submitted in Round 1, untouched)
  data/round1/annotation_sources/*.txt                (150 new hand-annotated notes, span markup)
Outputs
  data/round1/annotated_corpus.csv      note_id,token,tag      (official BIO format)
  data/round1/notes_raw.csv             note_id,text           (plain text used by RAG)
  data/round1/note_metadata.csv         note_id,domain,source_category,generator,batch,annotation_method
  round1_deliverables/validation_report.txt   (official validate.py output)

Run:  python scripts/build_corpus.py
"""
import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from medbhasha import corpus  # noqa: E402
from medbhasha.config import R1  # noqa: E402

# ---- Targeted consistency fixes to the 40 Round-1 notes -------------------------------------------
# (note_id, token, expected_old_tag, new_tag, reason)   each rule must match exactly one token
FIXES = [
    ("n014", "ইনহেলার", "B-DOSAGE", "I-MEDICATION", "dosage form is part of the MEDICATION span (convention C4)"),
    ("n029", "স্প্রে", "B-DOSAGE", "I-MEDICATION", "dosage form is part of the MEDICATION span (convention C4)"),
    ("n024", "ফলো-আপ", "I-TEMPORAL", "O", "'follow-up' is not a time expression; the time is 'এক সপ্তাহ পর'"),
    ("n028", "কোনো", "B-NEGATION_UNCERTAINTY", "O", "only the marker itself is tagged (schema section 3); 'কোনো' is a quantifier"),
    ("n040", "নিয়মিত", "B-DOSAGE", "O", "'regular walking' is advice, not a medication frequency"),
    ("n018", "পাথর", "B-DIAGNOSIS", "B-TEST_RESULT", "imaging finding reported by ultrasound -> TEST_RESULT (convention C6)"),
]
# multi-token fixes: (note_id, [(token, old_tag, new_tag), ...]) matched as a consecutive run
RUN_FIXES = [
    ("n019", [("খালি", "O", "I-DOSAGE"), ("পেটে", "B-BODY_SITE", "I-DOSAGE")],
     "'সকালে খালি পেটে' is one dosage-timing phrase"),
    ("n040", [("খালি", "O", "B-TEST"), ("পেটের", "B-BODY_SITE", "I-TEST"), ("শর্করা", "B-TEST", "I-TEST")],
     "'খালি পেটের শর্করা' (fasting sugar) is one TEST span"),
]
# Round-1 domain labels (project field; 'Respiratory Medicine' is unified with 'Respiratory'). Re-derived from note content so that they agree with the
# counts in the original declaration (GM 10, Cardiology 7, GI 8, Respiratory 9, Dermatology 6).
R1_DOMAIN = {}
for i in (1, 2, 3, 4, 35, 36, 37):
    R1_DOMAIN[f"n{i:03d}"] = "Cardiology"
for i in (5, 6, 7, 8, 9, 10, 11, 38, 39, 40):
    R1_DOMAIN[f"n{i:03d}"] = "General Medicine"
for i in (12, 13, 14, 15, 16, 27, 28, 29, 30):
    R1_DOMAIN[f"n{i:03d}"] = "Respiratory"
for i in (17, 18, 19, 20, 31, 32, 33, 34):
    R1_DOMAIN[f"n{i:03d}"] = "Gastroenterology"
for i in range(21, 27):
    R1_DOMAIN[f"n{i:03d}"] = "Dermatology"


def apply_fixes(notes):
    log = []
    for nid, tok, old, new, why in FIXES:
        toks, tags = notes[nid]
        hits = [i for i, (t, g) in enumerate(zip(toks, tags)) if t == tok and g == old]
        assert len(hits) == 1, (nid, tok, old, hits)
        tags[hits[0]] = new
        log.append((nid, tok, old, new, why))
    for nid, run, why in RUN_FIXES:
        toks, tags = notes[nid]
        n = len(run)
        hits = [i for i in range(len(toks) - n + 1)
                if all(toks[i + k] == run[k][0] and tags[i + k] == run[k][1] for k in range(n))]
        assert len(hits) == 1, (nid, run, hits)
        for k in range(n):
            tags[hits[0] + k] = run[k][2]
        log.append((nid, " ".join(r[0] for r in run), "/".join(r[1] for r in run), "/".join(r[2] for r in run), why))
    return log


def fix_bio(tags):
    """After edits make sure no orphan I- remains (turn it into B-)."""
    prev = "O"
    for i, g in enumerate(tags):
        if g.startswith("I-") and prev[2:] != g[2:]:
            tags[i] = "B-" + g[2:]
        prev = tags[i]
    return tags


def main():
    r1 = corpus.read_bio_csv(R1 / "round1_submitted_annotated_corpus.csv")
    log = apply_fixes(r1)
    out, raw, meta = [], [], []
    for nid, (toks, tags) in r1.items():
        tags = fix_bio(tags)
        out.append((nid, toks, tags))
        raw.append((nid, corpus.detokenize(toks)))
        meta.append((nid, R1_DOMAIN[nid],
                     "Synthetic clinical notes generated by team (fictional; not real patient data)",
                     "assistant-authored in conversation; no external source",
                     "round1_submitted", "LLM-assisted manual drafting; deterministic span->BIO alignment"))
    seen = set(r1)
    for nid, domain, text, toks, tags in corpus.read_sources():
        assert nid not in seen, f"duplicate note id {nid}"
        seen.add(nid)
        out.append((nid, toks, tags))
        raw.append((nid, text))
        batch = "round2_prep_expansion"
        meta.append((nid, domain,
                     "Synthetic clinical notes generated by team (fictional; not real patient data)",
                     "assistant-authored in conversation; no external source", batch,
                     "LLM-assisted manual drafting; deterministic span->BIO alignment"))
    out.sort(key=lambda x: x[0])
    raw.sort(key=lambda x: x[0])
    meta.sort(key=lambda x: x[0])

    corpus.write_bio_csv(R1 / "annotated_corpus.csv", out)
    with open(R1 / "notes_raw.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["note_id", "text"])
        w.writerows(raw)
    with open(R1 / "note_metadata.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["note_id", "domain", "source_category", "generator", "batch", "annotation_method"])
        w.writerows(meta)
    with open(ROOT / "round1_deliverables" / "round1_fixes_log.tsv", "w", encoding="utf-8") as f:
        f.write("note_id\ttoken(s)\told_tag\tnew_tag\treason\n")
        for row in log:
            f.write("\t".join(row) + "\n")

    # official validator -> mandatory report
    r = subprocess.run([sys.executable, str(ROOT / "resources" / "validate.py"),
                        "--input", str(R1 / "annotated_corpus.csv"), "--scheme", "BIO",
                        "--report", str(ROOT / "round1_deliverables" / "validation_report.txt")],
                       capture_output=True, text=True)
    print(r.stdout)
    if r.returncode != 0:
        print(r.stderr)
        sys.exit(r.returncode)


if __name__ == "__main__":
    main()
